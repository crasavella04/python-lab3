    ("Научный контент", "Интерактивные визуализации", 4, [2, 3, 1, 3]),
    ("Научный контент", "Исполнение ноутбуков и кэш", 8, [1, 3, 0, 3]),
    ("Научный контент", "Библиография BibTeX", 6, [1, 3, 0, 3]),
    ("Научный контент", "Сноски, глоссарий, нумерация разделов", 4, [2, 3, 1, 3]),
    ("Вёрстка и шаблоны", "Многоколоночная вёрстка", 4, [3, 3, 1, 3]),
    ("Вёрстка и шаблоны", "Шаблоны и частичное переопределение темы", 6, [3, 3, 3, 1]),
    ("Вёрстка и шаблоны", "Единый источник → PDF/LaTeX", 10, [1, 3, 0, 3]),
